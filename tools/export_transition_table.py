"""Regenerate the reviewable DFA table from the actual runtime definitions."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.dfa_engine import ALPHABET, STATES, TRANSITIONS, INITIAL_STATE, ACCEPTING_STATES, DEAD_STATE


def export():
    lines = ["# DFA transition table", "", "Generated by `python tools/export_transition_table.py` from `core/dfa_engine.py`.",
             "", f"Initial state: **{INITIAL_STATE}**. Accepting states: **{', '.join(sorted(ACCEPTING_STATES))}**. Reject state: **{DEAD_STATE}**.",
             "H is accepting only after EOF; reaching H on the semicolon alone is not sufficient.",
             "INT includes the mandatory space/tab separator. SPACE is optional boundary whitespace.",
             "WORD_GAP marks spaces between word/number lexemes; MISSING_SPACE marks int without its separator.",
             "LETTER, UNDERSCORE, and DIGIT are individual identifier/number characters. EOF is explicit end of input.", "",
             "| State | " + " | ".join(category.value for category in ALPHABET) + " |",
             "| --- | " + " | ".join("---" for _ in ALPHABET) + " |"]
    for state in STATES:
        lines.append("| " + state + " | " + " | ".join(TRANSITIONS[state, category] for category in ALPHABET) + " |")
    lines += ["", "All pairs have exactly one destination; DEAD is absorbing.",
              "G loops on DIGIT (the approved correction), preserving the distinction from the first operand in E.",
              "The spelling int in an identifier is read as LETTER characters in B/C.",
              "The diagram groups categories with the same origin and destination. Its 'other' edges",
              "mean exactly the categories assigned to DEAD in this table.", ""]
    (ROOT / "docs" / "transition_table.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    export()
